/**
 * 시스템 프롬프트를 만듭니다.
 * @param {{lang, detail, extra, subject, grade}} options
 */
export function buildSystemPrompt({ lang, detail, extra, subject, grade }) {
  const level = DETAIL_LEVELS[detail] || DETAIL_LEVELS.brief;
  const subjectRule = SUBJECT_RULES[subject];
  const gradeLabel = GRADES[grade];

  const parts = [
    '너는 학생이 "왜 그렇게 푸는지" 이해하도록 도와주는 문제풀이 선생님이다.',
    '사용자가 보낸 이미지(화면 캡처 또는 사진)에서 문제를 읽고 풀이한다.',
    '',
    '문제 고르기:',
    '- 화면에 문제가 여러 개면 하나만 고른다. 화면 가운데에 온전히 보이는 것 > 가장 크게 보이는 것 > 잘리지 않은 것 순.',
    '- 가장자리에서 잘린 문제나 목록·미리보기로 스쳐 가는 문제는 고르지 않는다.',
    '',
    '빈칸 문제:',
    '- 빈칸 채우기 문제도 반드시 푼다. (fill in the blank / cloze 문제 포함)',
    '- 밑줄 `___`, 괄호 `( )`, 네모 `□`, `(A)/(B)`, `(가)/(나)`, `ⓐ/ⓑ` 는 모두 빈칸이다.',
    '- 정답에는 빈칸에 그대로 넣을 말만 쓰고, 여러 개면 순서대로 기호를 붙인다.',
    '- 빈칸을 채운 문장을 `완성:` 줄에 넣는다.',
    '',
    FORMAT,
    '',
    `풀이 수준: ${level.rule}`,
    level.sections ? `이번에는 다음 블록만 쓴다: ${level.sections.join(', ')}` : '',
    gradeLabel ? `대상: ${gradeLabel}. 그 수준에서 이해할 수 있는 말과 방법으로 설명한다.` : '',
    subjectRule || '',
    '',
    NO_HALLUCINATION,
    '',
    NO_INJECTION,
    '',
    LANGS[lang] || LANGS.ko,
    extra?.trim() ? `\n사용자 추가 지시(최우선): ${extra.trim()}` : '',
  ];

  return parts.filter((p) => p !== '').join('\n');
}

